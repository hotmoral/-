#!/usr/bin/env python3
"""T1 Stage49-50 transition-aware integrated diagnostic v0.1.

This probe combines only two already-isolated findings:
1) Archer LINE opportunity is contaminated when it directly follows the
   off-axis DURABLE_SCATTER grammar and the earlier BRUTE remains frontmost.
2) Mage CLUSTER needs a bounded durable center to remain a multi-target
   opportunity at the common P×P timing.

No class/monster scalar, action cadence, shop/EXP, or production rule changes.
No authoring adoption is made here.

Transition-aware orders:
  Stage49: DURABLE_SCATTER -> FRONTLINE -> LINE -> CLUSTER
  Stage50: DURABLE_SCATTER -> FRONTLINE -> CLUSTER -> LINE -> LINE_REPRISE

Stage49 does not require Mage opportunity. Stage50 is the all-class synthesis.
Three Stage50 CLUSTER morphologies are compared under the exact same order:
  CONTROL, DURABLE_CORE_2, DURABLE_CORE_3.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

import probe_t1_stage49_50_order_robustness_v0_1 as orderprobe
import probe_t1_stage49_50_target_phase_clearance_v0_1 as target
import probe_t1_archer_lv31_continuous_corridor_bridge_v0_1 as widthbridge
import probe_t1_stage50_mage_cluster_persistence_v0_1 as magecluster
import t1_transition_microsim_mage_lv31_fidelity_bridge_v0_1 as magebridge

r = orderprobe.r
WIDTH = orderprobe.WIDTH
GAP_MS = orderprobe.GAP_MS
OFF = orderprobe.OFF
ON = orderprobe.ON

ORDER = {
    49: ["DURABLE_SCATTER", "FRONTLINE", "LINE", "CLUSTER"],
    50: ["DURABLE_SCATTER", "FRONTLINE", "CLUSTER", "LINE", "LINE_REPRISE"],
}
MORPHOLOGIES = {
    k: magecluster.CANDIDATES[k]
    for k in ("CONTROL", "DURABLE_CORE_2", "DURABLE_CORE_3")
}


def build_candidate(source: dict, morphology_id: str):
    doc = copy.deepcopy(source)
    by = {int(x["stage"]): x for x in doc["recipes"]}
    for stage in (49, 50):
        by[stage]["spawns"] = orderprobe.distinct.build_stage(ORDER[stage], GAP_MS)
        by[stage]["formation"] = "F08" if stage == 49 else "F01"
        by[stage]["formationSet"] = ["F01", "F02", "F03", "F08"]
        by[stage]["cadence"] = "CD05"
        by[stage]["pressureTags"] = ["BASELINE", "FLOOD", "RUSH", "BULWARK"]

    # Replace only the Stage50 CLUSTER phase body morphology. Spawn chronology
    # inside the grammar remains the same six offsets generated by build_stage.
    cluster_rows = [
        row for row in by[50]["spawns"]
        if target.distinct.phase_for_ms(int(row["tMs"]), GAP_MS, ORDER[50]) == "CLUSTER"
    ]
    if len(cluster_rows) != 6:
        raise r.RunnerFidelityError(f"expected six Stage50 CLUSTER rows, got {len(cluster_rows)}")
    for row, (typ, y) in zip(cluster_rows, MORPHOLOGIES[morphology_id]):
        row["type"] = typ
        row["y"] = y

    doc["version"] = f"{source['version']}+TRANSITION_AWARE_{morphology_id}"
    doc["status"] = "EPHEMERAL_TRANSITION_AWARE_INTEGRATION_NOT_AUTHORING"
    return doc


def execute_target_phase(doc: dict, p3: dict, p4: dict, temporal: dict, seeds):
    runtime = r.build_runtime(doc, p3, p4, temporal)
    by = {int(x["stage"]): x for x in doc["recipes"]}
    rows = []
    fidelity = []
    for cls in r.CLASSES:
        for seed in seeds:
            off1 = target.run_side(runtime, by, cls, seed, OFF, GAP_MS, ORDER)
            off2 = target.run_side(runtime, by, cls, seed, OFF, GAP_MS, ORDER)
            on1 = target.run_side(runtime, by, cls, seed, ON, GAP_MS, ORDER)
            on2 = target.run_side(runtime, by, cls, seed, ON, GAP_MS, ORDER)
            if r.sha256_obj(off1) != r.sha256_obj(off2):
                fidelity.append(f"OFF/determinism/{cls}/{seed}")
            if r.sha256_obj(on1) != r.sha256_obj(on2):
                fidelity.append(f"ON/determinism/{cls}/{seed}")
            fidelity.extend(f"OFF/{e}" for e in off1["continuityErrors"])
            fidelity.extend(f"ON/{e}" for e in on1["continuityErrors"])
            rows.append({"class": cls, "seed": seed, "OFF": off1, "ON": on1})
    return rows, target.aggregate(rows, ORDER), fidelity


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--recipes", required=True)
    ap.add_argument("--p3", default="legacy-game-structure/data/p3_ten_stage_fixture_v0_1.json")
    ap.add_argument("--p4d2-base", default="legacy-game-structure/data/p4d2_lv31_pressure_probe_fixture_v0_1.json")
    ap.add_argument("--p4d2-temporal", default="legacy-game-structure/data/p4d2_stage46_temporal_pressure_fixture_v0_1.json")
    ap.add_argument("--seeds", default="101,211,307,409,503")
    ap.add_argument("--json-out", required=True)
    args = ap.parse_args()

    source = r.load_yaml(args.recipes)
    p3 = r.load_json(args.p3)
    p4 = r.load_json(args.p4d2_base)
    temporal = r.load_json(args.p4d2_temporal)
    seeds = tuple(int(x) for x in args.seeds.split(",") if x.strip())
    source_by = {int(x["stage"]): x for x in source["recipes"]}

    candidates = {}
    all_fidelity = []
    for mid in MORPHOLOGIES:
        doc = build_candidate(source, mid)
        by = {int(x["stage"]): x for x in doc["recipes"]}
        static_errors = list(r.static_recipe_gate(doc))
        for stage in source_by:
            if stage not in (49, 50) and by[stage] != source_by[stage]:
                static_errors.append(f"scope-change-stage{stage}")
        stage_static = {str(s): orderprobe.shape.stage_static(by[s]) for s in (49, 50)}
        if any(v["max4s"] > 8 for v in stage_static.values()):
            static_errors.append("AUTHORED_4S_DENSITY_EXCEEDS_NORMAL_CAP")
        if static_errors:
            candidates[mid] = {"staticErrors": static_errors, "stageStatic": stage_static}
            continue

        overall = magebridge.with_mage_lv31_fidelity(
            lambda doc=doc: widthbridge.with_archer_final_width(
                WIDTH,
                lambda: orderprobe.shape.execute_candidate(doc, p3, p4, temporal, seeds),
            )
        )
        all_fidelity.extend(f"{mid}/overall/{e}" for e in overall["fidelityErrors"])

        phase_rows, phase_agg, phase_fidelity = magebridge.with_mage_lv31_fidelity(
            lambda doc=doc: widthbridge.with_archer_final_width(
                WIDTH,
                lambda: execute_target_phase(doc, p3, p4, temporal, seeds),
            )
        )
        all_fidelity.extend(f"{mid}/phase/{e}" for e in phase_fidelity)

        roles = {}
        for cls in r.CLASSES:
            off = orderprobe.role_stats(phase_agg, cls, "OFF")
            on = orderprobe.role_stats(phase_agg, cls, "ON")
            roles[cls] = {"OFF": off, "ON": on, "delta": orderprobe.role_delta(off, on)}
            if cls == "tank":
                boff = overall["OFF"]["byClass"]["tank"]
                bon = overall["ON"]["byClass"]["tank"]
                roles[cls]["objectiveProtection"] = {
                    "offWallDamage": boff["totalWallDamage"],
                    "onWallDamage": bon["totalWallDamage"],
                    "wallDamageReduction": round(boff["totalWallDamage"] - bon["totalWallDamage"], 6),
                    "offControlTotals": boff["controlTotals"],
                    "onControlTotals": bon["controlTotals"],
                }

        candidates[mid] = {
            "staticErrors": [],
            "stageStatic": stage_static,
            "clusterBodies": MORPHOLOGIES[mid],
            "overall": overall,
            "phaseAggregate": phase_agg,
            "phaseRows": phase_rows,
            "roles": roles,
        }

    out = {
        "version": "t1-stage49-50-transition-aware-integration-probe-v0.1",
        "status": "DIAGNOSTIC_INTEGRATION_NO_AUTHORING_OR_SCALAR_ADOPTION",
        "sourceRecipe": str(args.recipes),
        "sourceRecipeSha256": r.sha256_bytes(Path(args.recipes).read_bytes()),
        "orders": ORDER,
        "phaseGapMs": GAP_MS,
        "archerWidthBridge": {"yTolerance": WIDTH, "status": "DIAGNOSTIC_ONLY_NOT_FROZEN"},
        "mageLv31FidelityBridge": magebridge.BRIDGE_METADATA,
        "seeds": list(seeds),
        "fidelityErrors": all_fidelity,
        "candidates": candidates,
    }
    Path(args.json_out).write_text(json.dumps(out, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    print("candidate class direction unresolvedDelta latencyPct offWall onWall")
    for mid, block in candidates.items():
        if block.get("staticErrors"):
            print(mid, "STATIC_REJECT", block["staticErrors"])
            continue
        for cls in r.CLASSES:
            role = block["roles"][cls]
            boff = block["overall"]["OFF"]["byClass"][cls]
            bon = block["overall"]["ON"]["byClass"][cls]
            print(
                mid, cls,
                role["delta"]["direction"],
                role["delta"]["unresolvedImprovement"],
                role["delta"]["clearLatencyImprovementPct"],
                boff["totalWallDamage"], bon["totalWallDamage"],
            )
        print("MAGE_PHASE", mid, json.dumps({
            "OFF": block["roles"]["mage"]["OFF"],
            "ON": block["roles"]["mage"]["ON"],
            "delta": block["roles"]["mage"]["delta"],
        }, sort_keys=True))
        print("ARCHER_PHASE", mid, json.dumps({
            "OFF": block["roles"]["archer"]["OFF"],
            "ON": block["roles"]["archer"]["ON"],
            "delta": block["roles"]["archer"]["delta"],
        }, sort_keys=True))
    if all_fidelity:
        raise SystemExit("TRANSITION_AWARE_INTEGRATION_FIDELITY_FAIL")


if __name__ == "__main__":
    main()
