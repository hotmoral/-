"""Timing Defense P5 Tank fixed-rank Stage49 shop-combat probe v0.1.

Purpose:
- combine the corrected P4 Tank Stage49 combat semantics with fixed Stage49 shop-rank profiles;
- include ATK / KNOCKBACK / FORTIFICATION / generic DEF simultaneously;
- preserve P2 incoming-wall order: generic DEF -> Tank Iron Wall -> shield -> wall HP;
- screen legacy-relative shop-effect magnitudes before any production freeze.

Important limitations:
- Tank only;
- CRIT / CRIT DAMAGE omitted from this first scalar lane;
- Fortification is modeled as fully retained starting Stage49 reserve, which is defense-favorable;
- ranks are fixed Stage49 snapshots, not purchased over the full run;
- no production values/content are frozen.
"""
from __future__ import annotations

